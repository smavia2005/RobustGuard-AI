
# RobustGuard AI - Video Deepfake Detection
# Mirage frame features + trained video classifier
# CPU only

from pathlib import Path
from functools import lru_cache
import tempfile
import os

import cv2
import numpy as np
import torch
import joblib
from PIL import Image

from mirage_detector import load_detector


ROOT = Path(__file__).resolve().parent.parent

VIDEO_MODEL_PATH = (
    ROOT / "training" / "outputs"
    / "video_classifier.joblib"
)

NUM_FRAMES = 5


def extract_video_features(video_path):
    cap = cv2.VideoCapture(str(video_path))

    try:
        if not cap.isOpened():
            raise ValueError("Video could not be opened.")

        frame_count = int(
            cap.get(cv2.CAP_PROP_FRAME_COUNT)
        )

        if frame_count <= 0:
            raise ValueError(
                "Could not determine video frames."
            )

        # Sample across the video timeline.
        positions = np.linspace(
            0.1, 0.9, NUM_FRAMES
        )

        frames = []

        for position in positions:
            frame_index = int(
                position * (frame_count - 1)
            )

            cap.set(
                cv2.CAP_PROP_POS_FRAMES,
                frame_index
            )

            ok, frame = cap.read()

            if not ok:
                raise ValueError(
                    "Could not decode a sampled frame."
                )

            rgb = cv2.cvtColor(
                frame,
                cv2.COLOR_BGR2RGB
            )

            frames.append(
                Image.fromarray(rgb)
            )

    finally:
        cap.release()

    processor, model = load_detector()

    inputs = processor(
        images=frames,
        return_tensors="pt"
    )

    with torch.inference_mode():
        logits = model(**inputs).logits

        if logits.shape[-1] != 2:
            raise ValueError(
                "Unexpected Mirage output."
            )

        probabilities = torch.softmax(
            logits, dim=-1
        )

    # Same mapping as working Mirage image detector:
    # 0 = Real, 1 = Fake
    fake_scores = (
        probabilities[:, 1]
        .cpu()
        .numpy()
        .astype(float)
    )

    # A lightweight video-level feature vector.
    features = np.concatenate([
        fake_scores,
        np.array([
            fake_scores.mean(),
            fake_scores.std(),
            fake_scores.min(),
            fake_scores.max(),
            np.abs(np.diff(fake_scores)).mean()
        ])
    ])

    return {
        "features": features.tolist(),
        "frame_scores": fake_scores.tolist(),
        "frames_analysed": len(frames)
    }


@lru_cache(maxsize=1)
def load_video_classifier():
    if not VIDEO_MODEL_PATH.is_file():
        raise FileNotFoundError(
            "Video classifier has not been trained yet."
        )

    # Load only the model generated by your project.
    return joblib.load(VIDEO_MODEL_PATH)


def predict_video_path(video_path):
    extracted = extract_video_features(video_path)

    classifier = load_video_classifier()

    X = np.array(
        [extracted["features"]],
        dtype=np.float64
    )

    probabilities = classifier.predict_proba(X)[0]
    classes = list(classifier.classes_)

    fake_score = float(
        probabilities[classes.index(1)]
    )

    real_score = float(
        probabilities[classes.index(0)]
    )

    prediction = (
        "Fake" if fake_score >= 0.5 else "Real"
    )

    return {
        "status": "success",
        "model_status": "ready",
        "model_name": "RobustGuard Video Frame Classifier",
        "prediction": prediction,
        "confidence": f"{max(fake_score, real_score) * 100:.2f}%",
        "class_scores": {
            "Fake": round(fake_score * 100, 2),
            "Real": round(real_score * 100, 2)
        },
        "frames_analysed": extracted["frames_analysed"],
        "frame_fake_scores": [
            round(x * 100, 2)
            for x in extracted["frame_scores"]
        ],
        "explanation": (
            f"The video was classified as {prediction}. "
            "Five video frames were analysed with "
            "the pretrained Mirage image classifier. "
            "A separate logistic regression model "
            "combined their scores into a video-level "
            "prediction. This method is experimental "
            "and cannot reliably detect every type "
            "of deepfake or temporal manipulation."
        )
    }


def detect_video_bytes(content, filename="video.mp4"):
    extension = Path(filename).suffix.lower()

    if extension not in (".mp4", ".webm"):
        raise ValueError("Unsupported video extension.")

    temp_path = None

    try:
        with tempfile.NamedTemporaryFile(
            delete=False,
            suffix=extension
        ) as temp:
            temp.write(content)
            temp_path = temp.name

        return predict_video_path(temp_path)

    finally:
        if temp_path and os.path.exists(temp_path):
            os.remove(temp_path)
